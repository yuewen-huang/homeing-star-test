"""Import 蝎女's reviewed editor data and render-only runtime, without retiming.

Run with Python 3. Source is read-only. Generated data/preloads are export-safe;
JSON copies and hashes remain available for review. No editor UI enters the game.
"""
from pathlib import Path
import hashlib
import json
import re
import shutil

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'smear-combo-demo'
GAME = ROOT / 'homeing-star-game'
ASSETS = 'assets/bosses/sandstorm_fighter'
RUNTIME = 'scripts/bosses/sandstorm_fighter/authored'
COMBOS = ('sandstorm_pressure', 'sandstorm_counter')
ACTION_IDS = dict(zip(
    ['待机', '刺拳', '摆拳', '肘击', '膝击', '升龙拳', '蓄力双拳', '跳跃落地',
     '刺踢', '侧身斜上踢', '凌空抽射', '断头台', '肘击地面', '伏虎霸王拳', '野蛮冲撞', '后空翻', '地面托马斯接空中膝撞'],
    ['idle', 'jab', 'hook', 'elbow', 'knee', 'uppercut', 'charged_punch', 'jump_land',
     'thrust_kick', 'rising_kick', 'aerial_kick', 'axe_kick', 'elbow_slam', 'tiger_punch', 'rush', 'backflip', 'thomas_knee']))

def write(relative, text):
    path = GAME / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8', newline='\n')

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def replace_once(text, old, new):
    assert text.count(old) == 1, ('Source runtime changed; review port', old[:100])
    return text.replace(old, new, 1)

def replace_function(text, name, replacement):
    pattern = rf'^func {name}\(.*?(?=^func |^static func |\Z)'
    text, count = re.subn(pattern, lambda _: replacement + '\n\n', text, count=1, flags=re.M | re.S)
    assert count == 1, name
    return text

def main():
    character_path = SOURCE / 'characters/sandstorm_fighter/character.json'
    character = json.loads(character_path.read_text(encoding='utf-8'))
    assert set(character['actions']) == set(ACTION_IDS)
    manifest = {'name': '蝎女', 'id': 'sandstorm_fighter', 'source': 'smear-combo-demo',
                'character_sha256': digest(character_path), 'assets': [], 'combos': {}, 'runtime': {}}
    textures = {}
    for action, spec in character['actions'].items():
        for sheet in spec['sheets']:
            source = character_path.parent / sheet['file']
            cell = [int(v) for v in spec['cell']]
            name = f"{ACTION_IDS[action]}_{cell[0]}x{cell[1]}_{int(sheet['count'])}f.png"
            dest = f'{ASSETS}/body/{name}'
            (GAME / dest).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, GAME / dest)
            textures[sheet['file']] = 'res://' + dest
            manifest['assets'].append({'action': action, 'source': sheet['file'], 'path': dest,
                                       'frames': int(sheet['count']), 'sha256': digest(source)})
    character['name'] = '第三章 · 蝎女'
    # Sheet names remain stable lookup keys; TEXTURES maps them to imported resources.
    character_text = json.dumps(character, ensure_ascii=False, indent=2)
    write(f'{ASSETS}/data/character.json', character_text + '\n')
    plans = {}
    for combo in COMBOS:
        source = SOURCE / f'combos/{combo}/combo.json'
        plans[combo] = source.read_text(encoding='utf-8')
        plan = json.loads(plans[combo])
        assert plan['transition_ghosts'] is True
        assert plan['annotation_source_sha256'] == manifest['character_sha256']
        write(f'{ASSETS}/data/{combo}.json', plans[combo])
        manifest['combos'][combo] = {'title': plan['title'], 'sha256': digest(source)}
    literal = lambda value: json.dumps(value, ensure_ascii=False)
    bundle = '# Generated by import_sandstorm_fighter.py; do not hand edit.\nextends RefCounted\n'
    bundle += 'const CHARACTER_JSON = ' + literal(character_text) + '\nconst COMBOS = {\n'
    bundle += ''.join(f'\t{literal(k)}: {literal(v)},\n' for k, v in plans.items()) + '}\n'
    bundle += 'const TEXTURES = {\n' + ''.join(f'\t{literal(k)}: preload({literal(v)}),\n' for k, v in textures.items()) + '}\n'
    write(f'{RUNTIME}/library_data.gd', bundle)

    # Preserve the editor renderer's dependency closure, with private class names.
    globals_ = {'SmearLibrary': 'vfx/smear_library.gd', 'SmearStyle': 'vfx/smear_style.gd',
                'SmearRibbon': 'vfx/smear_ribbon.gd', 'RenderCaps': 'vfx/vendor_studio/render_caps.gd',
                'ComboStyle': 'vfx/vendor_studio/combo_style.gd'}
    pending = ['vfx/arranged_track_player.gd']
    sources = {}
    while pending:
        relative = pending.pop()
        if relative in sources:
            continue
        text = (SOURCE / relative).read_text(encoding='utf-8')
        if relative == 'vfx/track_preview.gd':
            # This character has fist/kick and quake tracks only. Do not import
            # unrelated sword/claw demo dependencies or their stage contracts.
            text = text.replace('const Claw = preload("res://vfx/track_claw.gd")\n', '')
            start = text.index('\t\t"sword":')
            end = text.index('\t\t"strike":', start)
            text = text[:start] + text[end:]
            start = text.index('\tif event.kind == "claw":', text.index('func _reaches_at_origin'))
            end = text.index('\nfunc _update_body()', start)
            text = text[:start] + '\treturn false\n' + text[end:]
        sources[relative] = text
        pending += [p for p in re.findall(r'res://(vfx/[^"\s]+\.(?:gdshaderinc|gdshader|gd))', text) if '%' not in p]
        pending += [path for name, path in globals_.items() if re.search(r'\b' + name + r'\b', text)]
    for relative, text in sources.items():
        manifest['runtime'][relative] = digest(SOURCE / relative)
        if relative == 'vfx/smear_library.gd':
            text = text.replace('res://characters/<id>/character.json', 'the imported character data bundle')
            text = text.replace('## Images load straight from disk, so new sheets work without a Godot reimport.', '## Textures are imported Godot resources explicitly referenced by the data bundle.')
            text = text.replace('extends RefCounted', 'extends RefCounted\nconst Data = preload("res://' + RUNTIME + '/library_data.gd")', 1)
            text = replace_once(text, '"res://characters/%s" % character_id', '"res://' + ASSETS + '/data"')
            start = text.index('\tvar path := folder.path_join("character.json")')
            end = text.index('\tfor action: String in', start)
            text = text[:start] + '\tdata = JSON.parse_string(Data.CHARACTER_JSON)\n\tdisplay_name = data.name\n\tscale = float(data.scale)\n\tvar presentation: Dictionary = {}\n' + text[end:]
            text = replace_function(text, '_image', 'func _image(file: String) -> Texture2D:\n\treturn Data.TEXTURES[file]')
            text = replace_function(text, 'save_poses', 'func save_poses() -> Error:\n\treturn ERR_UNAUTHORIZED')
        elif relative == 'vfx/annotation_tracks.gd':
            text = replace_function(text, 'save', 'func save(_lib: SmearLibrary) -> Error:\n\treturn ERR_UNAUTHORIZED')
        elif relative == 'vfx/track_player.gd':
            text = text.replace('var data: Dictionary = JSON.parse_string(FileAccess.get_file_as_string(combo_file))', 'var data: Dictionary = JSON.parse_string(SmearLibrary.Data.COMBOS[combo_file])')
            text = text.replace('\tcurrent.closed.connect(func() -> void: get_tree().change_scene_to_file("res://main.tscn"))\n', '')
            start = text.index('\t\telif not current.running')
            text = text[:start]  # Manual single shot: no editor auto-replay.
        elif relative == 'vfx/track_preview.gd':
            start = text.index('\tvar controls := HBoxContainer.new()')
            end = text.index('\nfunc _close()', start)
            text = text[:start] + '\t_last = float(document.duration)\n\tfor event: Dictionary in document.events: _last = maxf(_last, effect_end(event))\n\treset()\n' + text[end:]
            text = replace_function(text, '_unhandled_input', 'func _unhandled_input(_event: InputEvent) -> void:\n\tpass')
            text = replace_function(text, '_draw', 'func _draw() -> void:\n\tpass')
        elif relative == 'vfx/arranged_track_player.gd':
            text = replace_function(text, '_ready', 'func _ready() -> void:\n\tplan = JSON.parse_string(SmearLibrary.Data.COMBOS[combo_file])\n\tsuper._ready()')
            text = replace_function(text, '_input', 'func _input(_event: InputEvent) -> void:\n\tpass')
            start = text.index('\t\tvar total := completed_hits')
            end = text.index('\n\tsuper._process(delta)', start)
            text = text[:start] + '\t\tfinished.emit()\n' + text[end:]
            text = text.replace('var _verify := false\n', '')
        for name in globals_:
            text = re.sub(r'\b' + name + r'\b', 'Sandstorm' + name, text)
        # Scripts remain owner-scoped; shaders are runtime assets, not source code.
        for reference in re.findall(r'res://vfx/[^"\s]+\.(?:gdshaderinc|gdshader|gd)', text):
            suffix = reference.removeprefix('res://vfx/')
            base = RUNTIME if suffix.endswith('.gd') else ASSETS + '/fx/authored'
            text = text.replace(reference, 'res://' + base + '/' + suffix)
        suffix = relative.removeprefix('vfx/')
        dest = f'{RUNTIME}/{suffix}' if suffix.endswith('.gd') else f'{ASSETS}/fx/authored/{suffix}'
        write(dest, '# Imported from the authored combo runtime; see import_manifest.json.\n' + text if suffix.endswith('.gd') else text)
    for filename in ('SOURCE.md', 'LICENSE'):
        write(f'{ASSETS}/fx/{filename}', (SOURCE / 'vfx/vendor_studio' / filename).read_text(encoding='utf-8'))
    manifest['frame_count'] = sum(item['frames'] for item in manifest['assets'])
    write(f'{ASSETS}/data/import_manifest.json', json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    print(f"Imported 蝎女: {len(textures)} sheets, {manifest['frame_count']} frames, {len(plans)} combos, {len(sources)} runtime dependencies")

if __name__ == '__main__':
    main()
