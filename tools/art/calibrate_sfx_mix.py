"""Measure WAV active-body energy and generate non-destructive playback trims.

K-shaped spectral weighting plus a relative 50 ms energy gate avoids comparing
silence/tails to the body of a transient. This is an active RMS proxy, not LUFS.
"""
from pathlib import Path
import json, math, struct
import numpy as np

ROOT = Path(__file__).resolve().parents[3]
GAME = ROOT/'homeing-star-game'
REPORT = ROOT/'homeing-star-test/artifacts/sfx-mix'
OUT = GAME/'assets/sideview/audio/sfx/mix_profile.json'

def samples(path):
    raw = path.read_bytes(); pos = 12; fmt = data = None
    while pos+8 <= len(raw):
        tag, length = struct.unpack_from('<4sI',raw,pos); pos += 8
        if tag==b'fmt ': fmt = raw[pos:pos+length]
        if tag==b'data': data = raw[pos:pos+length]
        pos += length+(length%2)
    code, channels, rate, _, _, bits = struct.unpack_from('<HHIIHH',fmt)
    if code==65534: code = struct.unpack_from('<H',fmt,24)[0]
    if code==3: audio = np.frombuffer(data,dtype='<f4' if bits==32 else '<f8').astype(float)
    elif bits==16: audio = np.frombuffer(data,dtype='<i2').astype(float)/32768
    elif bits==24:
        b = np.frombuffer(data,dtype=np.uint8).reshape(-1,3).astype(np.int32)
        n = b[:,0]+(b[:,1]<<8)+(b[:,2]<<16)
        audio = ((n^0x800000)-0x800000)/8388608
    elif bits==32: audio = np.frombuffer(data,dtype='<i4').astype(float)/2147483648
    elif bits==8: audio = (np.frombuffer(data,dtype=np.uint8).astype(float)-128)/128
    else: raise ValueError(f'Unsupported format: {path}: {code}/{bits}')
    return audio.reshape(-1,channels),rate

def db(amplitude): return 20*math.log10(max(float(amplitude),1e-9))

def weighted(audio,rate):
    # Frequency-domain magnitudes of a 4 dB high shelf and a 38 Hz high pass.
    size = 1 << (len(audio)*2-1).bit_length()
    frequency = np.fft.rfftfreq(size,1/rate)
    z = np.exp(-2j*np.pi*frequency/rate)
    def response(b,a): return abs((b[0]+b[1]*z+b[2]*z*z)/(a[0]+a[1]*z+a[2]*z*z))
    w = 2*np.pi*38.135/rate; c = np.cos(w); alpha = np.sin(w)/(2*.500327)
    highpass = response([(1+c)/2,-(1+c),(1+c)/2],[1+alpha,-2*c,1-alpha])
    w = 2*np.pi*1681.974/rate; c = np.cos(w); alpha = np.sin(w)/(2*.707175)
    A = 10**(4/40); s = 2*np.sqrt(A)*alpha
    shelf = response([A*((A+1)+(A-1)*c+s),-2*A*((A-1)+(A+1)*c),A*((A+1)+(A-1)*c-s)],
                     [(A+1)-(A-1)*c+s,2*((A-1)-(A+1)*c),(A+1)-(A-1)*c-s])
    return np.fft.irfft(np.fft.rfft(audio,n=size,axis=0)*(highpass*shelf)[:,None],n=size,axis=0)[:len(audio)]

def main():
    REPORT.mkdir(parents=True,exist_ok=True)
    rows = {}
    for path in sorted((GAME/'assets').rglob('*.wav')):
        audio,rate = samples(path)
        peak = db(np.max(abs(audio)))
        signal = weighted(audio,rate)
        size = max(1,int(rate*.05))
        energy = np.array([np.mean(np.sum(block*block,axis=1)) for block in np.array_split(signal,max(1,len(signal)//size))])
        gate = max(energy.max()*.0031623,1e-12) # -25 dB relative to the loudest block.
        active = energy[energy>=gate]
        level = 10*math.log10(max(float(active.mean()) if len(active) else 0,1e-12))
        trim = float(np.clip(-22-level,-30,12)) if peak>-80 else 0
        rows['res://'+path.relative_to(GAME).as_posix()] = {
            'peak_dbfs':round(peak,3),'active_weighted_db':round(level,3),'trim_db':round(trim,3)}
    profile = {'reference_active_db':-22,'peak_ceiling_dbfs':-3,'sounds':rows}
    OUT.write_text(json.dumps(profile,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    # Preloaded GDScript data ships in exports without non-resource JSON filters.
    OUT.with_suffix('.gd').write_text('extends RefCounted\n# Generated by calibrate_sfx_mix.py; do not edit.\nconst DATA := '+json.dumps(profile,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (REPORT/'measurements.json').write_text(json.dumps(profile,ensure_ascii=False,indent=2),encoding='utf-8')
    for uri,row in rows.items():
        if any(token in uri for token in ['/swing/','lan_voice/','ui_pop','roar_giant','/crystal_crab/']):
            print(Path(uri).name,row)
    print('Measured',len(rows),'WAV files; original audio unchanged.')

if __name__=='__main__': main()
